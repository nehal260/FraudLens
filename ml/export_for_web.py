#!/usr/bin/env python3
"""
FraudLens - export for the website
==================================
Reads what train_model.py produced and writes small .js data files into
../web/data/ so the site can run completely in the browser (no server).

    forest.js    the trained random forest, flattened so JavaScript can score with it
    results.js   confusion matrices, metrics and threshold sweeps for the 3 models
    pool.js      300 held-out transactions used by the samples picker and Live Monitor
    stats.js     dataset facts used by the "About the Data" tab (amount, hour, features)
    ../assets/sample_transactions.csv   a ready-made file for the CSV tab

Usage
    python export_for_web.py                 # real data (data/creditcard.csv)
    python export_for_web.py --demo          # if you trained with --demo
"""
import argparse
import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

HERE = Path(__file__).parent
WEB = HERE.parent / "web"
ART = HERE / "artifacts"
SEED = 11


def r(x, nd=5):
    """round floats so the files stay small"""
    return float(f"{x:.{nd}g}")


def write_js(name, var, obj):
    path = WEB / "data" / name
    path.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(obj, separators=(",", ":"))
    path.write_text(f"/* generated by ml/export_for_web.py - do not edit by hand */\nwindow.{var}={body};\n")
    print(f"  wrote web/data/{name:<12} {path.stat().st_size/1024:8.1f} KB")


def export_forest(forest, features):
    feat, thr, left, right, val, roots = [], [], [], [], [], []
    for est in forest.estimators_:
        t = est.tree_
        roots.append(len(feat))
        base = len(feat)
        v = t.value[:, 0, :]
        p1 = v[:, 1] / np.maximum(v.sum(axis=1), 1e-12)
        for i in range(t.node_count):
            is_leaf = t.children_left[i] == -1
            feat.append(-1 if is_leaf else int(t.feature[i]))
            thr.append(0 if is_leaf else r(t.threshold[i], 7))
            left.append(-1 if is_leaf else int(t.children_left[i]) + base)
            right.append(-1 if is_leaf else int(t.children_right[i]) + base)
            val.append(r(p1[i], 4) if is_leaf else 0)
    return {"features": features, "roots": roots, "feat": feat, "thr": thr,
            "left": left, "right": right, "val": val}


def sweep(y, p):
    out = []
    for t in np.round(np.arange(0, 1.0001, 0.01), 2):
        pred = p >= t
        tp = int(((pred) & (y == 1)).sum())
        fp = int(((pred) & (y == 0)).sum())
        fn = int(((~pred) & (y == 1)).sum())
        out.append([float(t), tp, fp, fn])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(HERE / "data" / "creditcard.csv"))
    ap.add_argument("--demo", action="store_true")
    args = ap.parse_args()

    metrics = json.loads((ART / "metrics.json").read_text())
    z = np.load(ART / "test_set.npz", allow_pickle=False)
    X, y, features = z["X_test"], z["y_test"], [str(f) for f in z["features"]]
    forest = joblib.load(HERE / "models" / "forest.joblib")
    p_forest = z["p_forest"]

    if args.demo or metrics["demo"]:
        from generate_demo_data import make_demo
        df = make_demo()
    else:
        df = pd.read_csv(args.data)

    print("Exporting for the website...")

    # 1. forest -------------------------------------------------------------
    fj = export_forest(forest, features)
    total_nodes = len(fj["feat"])
    if total_nodes > 600_000:
        print(f"  warning: forest has {total_nodes:,} nodes; the page may load slowly. "
              "Retrain with fewer trees (--trees 60) if so.")
    write_js("forest.js", "FL_FOREST", fj)

    # 2. results ------------------------------------------------------------
    models = []
    for m in metrics["models"]:
        m = dict(m)
        m["sweep"] = sweep(y, z[f"p_{m['key']}"])
        models.append(m)
    hist_n, edges = np.histogram(p_forest[y == 0], bins=20, range=(0, 1))
    hist_f, _ = np.histogram(p_forest[y == 1], bins=20, range=(0, 1))
    write_js("results.js", "FL_RESULTS", {
        "demo": metrics["demo"], "threshold": metrics["threshold"],
        "rows": metrics["rows"], "frauds": metrics["frauds"],
        "train_rows": metrics["train_rows"], "test_rows": metrics["test_rows"],
        "test_frauds": metrics["test_frauds"], "trees": len(forest.estimators_),
        "models": models,
        "scoreHist": {"normal": hist_n.tolist(), "fraud": hist_f.tolist()}})

    # 3. pool of held-out transactions -------------------------------------
    rng = np.random.default_rng(SEED)
    idx_f = np.flatnonzero(y == 1)
    idx_n = np.flatnonzero(y == 0)
    take_f = rng.choice(idx_f, size=min(30, len(idx_f)), replace=False)
    hardest = idx_n[np.argsort(-p_forest[idx_n])[:4]]
    rest = np.setdiff1d(idx_n, hardest)
    take_n = rng.choice(rest, size=300 - len(take_f) - len(hardest), replace=False)
    pick = np.concatenate([take_n, hardest, take_f])
    rng.shuffle(pick)
    rows = [[r(v, 6) for v in X[i]] for i in pick]
    labels = [int(y[i]) for i in pick]
    pp = {int(i): float(p_forest[i]) for i in pick}
    order_n = [k for k, i in enumerate(pick) if y[i] == 0]
    order_f = [k for k, i in enumerate(pick) if y[i] == 1]
    by_n = sorted(order_n, key=lambda k: pp[int(pick[k])])
    by_f = sorted(order_f, key=lambda k: -pp[int(pick[k])])
    # a teaching mix: clearly normal, odd-looking normal, obvious fraud, sneaky fraud
    samples = ([{"i": k, "tag": "clear"} for k in by_n[:4:1]] +
               [{"i": k, "tag": "odd"} for k in by_n[-2:]] +
               [{"i": k, "tag": "obvious"} for k in by_f[:3]] +
               [{"i": k, "tag": "sneaky"} for k in by_f[-2:]])
    rng.shuffle(samples)
    write_js("pool.js", "FL_POOL", {
        "features": features, "rows": rows, "y": labels,
        "samples": samples})

    csv = pd.DataFrame(rows, columns=features)
    csv["Class"] = labels
    (WEB / "assets").mkdir(parents=True, exist_ok=True)
    csv.to_csv(WEB / "assets" / "sample_transactions.csv", index=False)
    print(f"  wrote web/assets/sample_transactions.csv ({len(csv)} rows)")

    # 4. dataset stats ------------------------------------------------------
    cls = df["Class"].to_numpy()
    amt_edges = [0, 1, 5, 10, 25, 50, 100, 250, 500, 1000, 1e12]
    amt_n, _ = np.histogram(df.loc[cls == 0, "Amount"], bins=amt_edges)
    amt_f, _ = np.histogram(df.loc[cls == 1, "Amount"], bins=amt_edges)
    hour = ((df["Time"] // 3600) % 24).astype(int)
    hr_n = np.bincount(hour[cls == 0], minlength=24)
    hr_f = np.bincount(hour[cls == 1], minlength=24)

    feat_meta = {}
    for f in features:
        col = df[f].to_numpy(dtype=float)
        lo, hi = np.percentile(col, [0.5, 99.5])
        if f == "Time":
            lo, hi = 0, 172800
        bins = np.linspace(lo, hi, 31)
        dn, _ = np.histogram(np.clip(col[cls == 0], lo, hi), bins=bins)
        df_, _ = np.histogram(np.clip(col[cls == 1], lo, hi), bins=bins)
        feat_meta[f] = {
            "median": r(float(np.median(col[cls == 0])), 6),
            "mean_n": r(float(col[cls == 0].mean()), 5), "mean_f": r(float(col[cls == 1].mean()), 5),
            "lo": r(float(np.percentile(col, 1)), 5), "hi": r(float(np.percentile(col, 99)), 5),
            "hlo": r(float(lo), 5), "hhi": r(float(hi), 5),
            "dn": (dn / max(dn.sum(), 1)).round(4).tolist(),
            "df": (df_ / max(df_.sum(), 1)).round(4).tolist()}
    imp = sorted(zip(features, forest.feature_importances_), key=lambda t: -t[1])
    write_js("stats.js", "FL_STATS", {
        "total": int(len(df)), "fraud": int(cls.sum()),
        "amountEdges": amt_edges[:-1] + [None], "amountNormal": amt_n.tolist(),
        "amountFraud": amt_f.tolist(), "hourNormal": hr_n.tolist(), "hourFraud": hr_f.tolist(),
        "amountMeanNormal": r(float(df.loc[cls == 0, "Amount"].mean()), 5),
        "amountMeanFraud": r(float(df.loc[cls == 1, "Amount"].mean()), 5),
        "importance": [[f, r(float(v), 4)] for f, v in imp],
        "feat": feat_meta})
    print("\nDone. Open web/index.html in a browser.")


if __name__ == "__main__":
    main()
